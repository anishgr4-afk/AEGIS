"""Emergency checklist lookup: reported symptoms + observed signs + live vitals
-> the Medical Checklist procedures to open, most urgent first.

The point: in an emergency the flight surgeon is many minutes away on
a Mars transit. Crewmates tap what they see, the wearables supply the vitals,
and the matching procedure PDFs come up immediately - nobody stops to take
and type in measurements.

Decision rules:  data/checklist_triage.json  (draft - needs team review)
Procedure index: data/checklist_sections.json
Split PDFs:      data/checklist/  (generated by scripts/split_checklist.py)

This only points to NASA's own procedures. It does not diagnose, and it never
suggests a medication itself. Simulated demo, not a medical device.
"""
from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any, Callable

from flask import Blueprint, abort, jsonify, request, send_from_directory

from clinical import SYMPTOM_IDS, SYMPTOMS, VITAL_RANGES, evaluate_vitals

ROOT = Path(__file__).resolve().parent
TRIAGE_FILE = ROOT / "data" / "checklist_triage.json"
PDF_DIR = ROOT / "data" / "checklist"
MANIFEST_FILE = PDF_DIR / "manifest.json"

TIER_RANK = {"emergency": 0, "urgent": 1, "routine": 2}
TIER_LABEL = {"emergency": "EMERGENCY", "urgent": "URGENT", "routine": "ROUTINE"}

VITAL_INFO: dict[str, tuple[str, str]] = {
    "heart_rate_bpm": ("Heart rate", "bpm"),
    "spo2_pct": ("SpO₂", "%"),
    "respiratory_rate_bpm": ("Breathing rate", "/min"),
    "bp_systolic": ("Systolic BP", "mmHg"),
    "body_temp_c": ("Core temperature", "°C"),
    "blood_sugar_mgdl": ("Blood sugar", "mg/dL"),
}
VITAL_LIMITS: dict[str, tuple[float, float]] = {
    **{k: VITAL_RANGES[k] for k in ("heart_rate_bpm", "spo2_pct", "respiratory_rate_bpm", "bp_systolic", "body_temp_c")},
    "blood_sugar_mgdl": (20, 600),
}
# telemetry.py signal -> vital name used here. Skin temperature is deliberately
# absent: it is not core temperature (see telemetry.py).
TELEMETRY_SIGNALS = {
    "heart_rate_bpm": "heart_rate_bpm",
    "spo2_pct": "spo2_pct",
    "respiratory_rate_bpm": "respiratory_rate_bpm",
    "bp_systolic_est": "bp_systolic",
    "blood_sugar_mgdl": "blood_sugar_mgdl",
}
FEVER_C = 38.0  # clinical.py 'act' threshold

DISCLAIMER = ("Simulated demo, not a medical device. Points to NASA Medical Checklist procedures "
              "(JSC-48031 Rev H, 2001); it does not diagnose or prescribe. Follow the Crew Medical Officer.")


def load_json(path: Path) -> dict:
    with path.open(encoding="utf-8") as fh:
        return json.load(fh)


class ChecklistTriage:
    def __init__(self, triage: dict | None = None, manifest: dict | None = None):
        self.triage = triage if triage is not None else load_json(TRIAGE_FILE)
        self.manifest = manifest if manifest is not None else (
            load_json(MANIFEST_FILE) if MANIFEST_FILE.is_file() else None)
        self.signs: dict[str, dict] = self.triage["signs"]
        self.rules: list[dict] = self.triage["rules"]
        self.not_covered: dict[str, str] = {k: v for k, v in self.triage["not_covered"].items() if not k.startswith("_")}
        self.sections: dict[str, dict] = {s["id"]: s for s in (self.manifest or {}).get("sections", [])}

    @property
    def ready(self) -> bool:
        return self.manifest is not None

    # -- inputs ------------------------------------------------------------

    def validate(self, symptoms: Any, signs: Any, vitals: Any) -> tuple[list[str], list[str], dict[str, float]]:
        if not isinstance(symptoms, list) or any(s not in SYMPTOM_IDS for s in symptoms):
            raise ValueError(f"symptoms must be a list of: {', '.join(sorted(SYMPTOM_IDS))}")
        if not isinstance(signs, list) or any(s not in self.signs for s in signs):
            raise ValueError(f"signs must be a list of: {', '.join(self.signs)}")
        if not isinstance(vitals, dict):
            raise ValueError("vitals must be an object of {signal: number}")
        clean: dict[str, float] = {}
        for key, value in vitals.items():
            if key not in VITAL_LIMITS:
                raise ValueError(f"unknown vital '{key}'; use: {', '.join(VITAL_LIMITS)}")
            low, high = VITAL_LIMITS[key]
            if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value) or not low <= value <= high:
                raise ValueError(f"{key} must be a number from {low} to {high}")
            clean[key] = float(value)
        return list(dict.fromkeys(symptoms)), list(dict.fromkeys(signs)), clean

    @staticmethod
    def vitals_from_telemetry(summary: dict | None) -> dict[str, dict]:
        """Usable live readings from telemetry.TelemetryStore.summary()."""
        out: dict[str, dict] = {}
        if not summary or not summary.get("feed", {}).get("online"):
            return out
        for signal, name in TELEMETRY_SIGNALS.items():
            s = summary.get("signals", {}).get(signal, {})
            if s.get("status") == "measured":
                out[name] = {"value": s["value"], "source": s.get("source_label", "wearable"),
                             "context": s.get("context", "rest"), "samples": s.get("samples")}
        return out

    # -- evaluation --------------------------------------------------------

    @staticmethod
    def _vital_holds(cond: dict, vitals: dict[str, dict]) -> bool:
        v = vitals.get(cond["signal"])
        if v is None or (cond.get("rest_only") and v.get("context", "rest") != "rest"):
            return False
        x = v["value"]
        return all((
            "lt" not in cond or x < cond["lt"], "lte" not in cond or x <= cond["lte"],
            "gt" not in cond or x > cond["gt"], "gte" not in cond or x >= cond["gte"],
        ))

    def _rule_fires(self, rule: dict, symptoms: set[str], signs: set[str], vitals: dict[str, dict]) -> bool:
        positive = ("signs_any", "signs_all", "symptoms_any", "symptoms_all", "vitals_all", "vitals_any")
        if not any(rule.get(k) for k in positive):
            return False
        checks = [
            not rule.get("signs_any") or any(s in signs for s in rule["signs_any"]),
            not rule.get("signs_all") or all(s in signs for s in rule["signs_all"]),
            not rule.get("signs_none") or not any(s in signs for s in rule["signs_none"]),
            not rule.get("symptoms_any") or any(s in symptoms for s in rule["symptoms_any"]),
            not rule.get("symptoms_all") or all(s in symptoms for s in rule["symptoms_all"]),
            not rule.get("vitals_all") or all(self._vital_holds(c, vitals) for c in rule["vitals_all"]),
            not rule.get("vitals_any") or any(self._vital_holds(c, vitals) for c in rule["vitals_any"]),
        ]
        return all(checks)

    def _section_ref(self, sid: str) -> dict:
        s = self.sections[sid]
        pages = s["start"] if s["start"] == s["end"] else f"{s['start']} to {s['end']}"
        return {"id": sid, "title": s["title"], "pages": pages, "pdf_url": f"/api/checklist/pdf/{sid}"}

    def evaluate(self, symptoms: list[str], signs: list[str], vitals: dict[str, dict],
                 one_way_delay_s: float = 0) -> dict[str, Any]:
        if not self.ready:
            raise RuntimeError("checklist PDFs not generated - run scripts/split_checklist.py")

        effective = set(symptoms)
        derived_fever = False
        temp = vitals.get("body_temp_c")
        if temp and temp["value"] > FEVER_C and "fever_chills" not in effective:
            effective.add("fever_chills")
            derived_fever = True

        sign_set = set(signs)
        used: set[str] = set()
        matches: dict[str, dict] = {}
        for rule in self.rules:
            if not self._rule_fires(rule, effective, sign_set, vitals):
                continue
            # Which inputs this rule actually relied on.
            for key in ("signs_any", "signs_all"):
                used.update(s for s in rule.get(key, []) if s in sign_set)
            for key in ("symptoms_any", "symptoms_all"):
                used.update(s for s in rule.get(key, []) if s in effective)
            vital_bits = []
            for cond in rule.get("vitals_all", []) + rule.get("vitals_any", []):
                if self._vital_holds(cond, vitals) and cond["signal"] not in used:
                    used.add(cond["signal"])
                    v = vitals[cond["signal"]]
                    label, unit = VITAL_INFO[cond["signal"]]
                    vital_bits.append(f"{label} {v['value']:g}{unit} from {v['source']}")
            if derived_fever and "fever_chills" in used:
                used.add("body_temp_c")
            reason = rule["reason"] + (f" ({'; '.join(vital_bits)})" if vital_bits else "")

            for position, sid in enumerate(rule["sections"]):
                entry = matches.setdefault(sid, {
                    **self._section_ref(sid), "tier": rule["tier"], "primary": False,
                    "_primary_tier": None, "reasons": [], "rules": [], "sources": [],
                    "surgeon_approval_meds": sorted({m["name"] for m in self.sections[sid]["surgeon_approval_meds"]}),
                })
                if TIER_RANK[rule["tier"]] < TIER_RANK[entry["tier"]]:
                    entry["tier"] = rule["tier"]
                if position == 0 and (entry["_primary_tier"] is None
                                      or TIER_RANK[rule["tier"]] < TIER_RANK[entry["_primary_tier"]]):
                    entry["_primary_tier"] = rule["tier"]
                if reason not in entry["reasons"]:
                    entry["reasons"].append(reason)
                entry["rules"].append(rule["id"])
                if rule["source"] not in entry["sources"]:
                    entry["sources"].append(rule["source"])

        # A section leads its tier only if some rule AT THAT TIER put it first.
        # Otherwise a weaker rule ("short of breath" -> Breathing Difficulty,
        # urgent) could promote a supporting page above the specific one
        # ("chest pain + short of breath" -> Chest Pain, emergency).
        for m in matches.values():
            m["primary"] = m.pop("_primary_tier") == m["tier"]
        ordered = sorted(matches.values(), key=lambda m: (
            TIER_RANK[m["tier"]], not m["primary"], self.sections[m["id"]].get("order", 99)))
        for m in ordered:
            m["related"] = [self._section_ref(r) for r in self.sections[m["id"]].get("related", [])
                            if r in self.sections and r not in matches]

        not_covered = self._not_covered(symptoms, vitals, used)
        round_trip_min = int((2 * one_way_delay_s) // 60)
        if ordered:
            top = ordered[0]
            headline = f"{TIER_LABEL[top['tier']]}: open {top['title']} (checklist p. {top['pages']})"
        else:
            headline = "No checklist procedure matches these inputs. Record vitals and contact the flight surgeon."

        return {
            "headline": headline,
            "tier": ordered[0]["tier"] if ordered else None,
            "matches": ordered,
            "not_covered": not_covered,
            "inputs": {"symptoms": symptoms, "signs": signs, "derived": ["fever_chills (temperature)"] if derived_fever else []},
            "vitals_used": vitals,
            "comms": {
                "one_way_delay_s": one_way_delay_s,
                "round_trip_min": round_trip_min,
                "note": (
                    f"Every 'Contact Surgeon' step takes at least {round_trip_min} min round trip. "
                    "Do every other step without waiting; the Crew Medical Officer decides in the meantime "
                    "(NASA-STD-3001 [V1 3000]: CMOs are the in-mission medical care providers)."
                ) if round_trip_min else "Surgeon reachable in near real time.",
            },
            "highlight_legend": {
                "blue": "where the procedure starts on a shared page",
                "orange": "medication marked * in the checklist: Contact Surgeon first",
            },
            "disclaimer": DISCLAIMER,
        }

    def _not_covered(self, symptoms: list[str], vitals: dict[str, dict], used: set[str]) -> list[dict]:
        out = []
        for s in symptoms:
            if s not in used:
                out.append({"input": s, "note": self.not_covered.get(
                    s, "No checklist procedure for this alone. Record it for the flight surgeon.")})
        # Abnormal vitals that no rule turned into a procedure. Rates and blood
        # pressure taken during exercise or recovery are expected to be high,
        # so they are not reported (same rule as telemetry.py).
        exercise_sensitive = {"heart_rate_bpm", "respiratory_rate_bpm", "bp_systolic"}
        at_rest = {k: v["value"] for k, v in vitals.items()
                   if k not in exercise_sensitive or v.get("context", "rest") == "rest"}
        flags = evaluate_vitals(at_rest)["flags"]
        flag_vital = {"blood_pressure": "bp_systolic"}
        for f in flags:
            key = flag_vital.get(f["id"], f["id"])
            if key in used:
                continue
            note = self.not_covered.get(key) or (
                "No checklist procedure for this reading alone. Record it for the flight surgeon.")
            if key == "body_temp_c":
                note = self.not_covered["fever_chills"]
            out.append({"input": f"{f['label']} {f['value']} {f['unit']}", "note": note, "threshold": f["threshold"]})
        return out


def create_checklist_blueprint(
    live_summary: Callable[..., dict] | None = None,
    comms_delay: Callable[[], float] | None = None,
    triage: ChecklistTriage | None = None,
) -> Blueprint:
    engine = triage or ChecklistTriage()
    bp = Blueprint("checklist", __name__)
    bp.engine = engine  # type: ignore[attr-defined]  # exposed for tests

    def not_ready():
        return jsonify({"error": "Checklist PDFs not generated. Run: python scripts/split_checklist.py"}), 503

    @bp.get("/api/checklist/inputs")
    def checklist_inputs():
        return jsonify({
            "symptoms": SYMPTOMS,
            "signs": [{"id": k, **v} for k, v in engine.signs.items()],
            "vitals": [{"id": k, "label": VITAL_INFO[k][0], "unit": VITAL_INFO[k][1]} for k in VITAL_LIMITS],
        })

    @bp.get("/api/checklist/sections")
    def checklist_sections():
        if not engine.ready:
            return not_ready()
        return jsonify([{**engine._section_ref(s["id"]), "group": s["group"],
                         "reference": s.get("reference", False),
                         "surgeon_approval_meds": sorted({m["name"] for m in s["surgeon_approval_meds"]})}
                        for s in engine.sections.values()])

    @bp.get("/api/checklist/pdf/<section_id>")
    def checklist_pdf(section_id: str):
        if not engine.ready:
            return not_ready()
        if section_id not in engine.sections:
            abort(404)
        return send_from_directory(PDF_DIR, engine.sections[section_id]["file"], mimetype="application/pdf")

    @bp.post("/api/checklist/match")
    def checklist_match():
        if not engine.ready:
            return not_ready()
        payload = request.get_json(silent=True)
        if not isinstance(payload, dict):
            return jsonify({"error": "Body must be a JSON object: {symptoms, signs, vitals?, use_live_vitals?}"}), 400
        try:
            symptoms, signs, entered = engine.validate(
                payload.get("symptoms", []), payload.get("signs", []), payload.get("vitals", {}))
        except ValueError as exc:
            return jsonify({"error": str(exc)}), 400
        vitals: dict[str, dict] = {}
        crew = payload.get("crew")  # whose wearables; omitted = the default wearer
        if crew is not None and not isinstance(crew, str):
            return jsonify({"error": "crew must be a crew id string"}), 400
        if payload.get("use_live_vitals", True) and live_summary is not None:
            try:
                summary = live_summary(crew) if crew else live_summary()
            except KeyError as exc:
                return jsonify({"error": exc.args[0]}), 400
            vitals.update(engine.vitals_from_telemetry(summary))
        for key, value in entered.items():  # entered values override live ones
            vitals[key] = {"value": value, "source": "entered by crew", "context": "rest"}
        delay = float(comms_delay()) if comms_delay else 0.0
        return jsonify(engine.evaluate(symptoms, signs, vitals, delay))

    return bp
